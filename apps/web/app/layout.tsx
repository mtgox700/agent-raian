export default function RootLayout({
  children,
}: {
  children: React.ReactNode
}) {
  return (
    <html
      lang={brand.locale}
      // Selects the brand's CSS variables (packages/themes → themes.generated.css).
      data-brand={brand.key}
      className={cn(syne.variable, inter.variable, mono.variable, playfair.variable)}
    >
      <head>
        <StructuredData schema={softwareAppSchema} />
        <StructuredData schema={organizationSchema} />
        {/* Without JavaScript the signature scenes show their end state. */}
        <noscript dangerouslySetInnerHTML={{ __html: '<style>.scene *{animation:none!important}</style>' }} />
      </head>
      <body className="bg-void text-white font-body antialiased">
        <a href="#main-content" className="skip-link">
          Aller au contenu principal
        </a>
        {/* PostHog wraps the whole app (analytics on every page incl. landing).
            Clerk is intentionally NOT here — it is scoped to (auth)/(dashboard)
            via <AuthProviders> so the public landing ships no auth SDK. */}
        <PostHogProvider>
          {/* LazyMotion: public components use the lightweight `m` component;
              framer's feature pack is code-split off the critical path. */}
          <LazyMotionProvider>
            {/* PostHogPageView uses useSearchParams — must be wrapped in Suspense */}
            <Suspense fallback={null}>
              <PostHogPageView />
            </Suspense>
            {children}
            {/* GDPR cookie consent — first-visit banner, persists choice for 12 months */}
            <CookieConsentBanner />
          </LazyMotionProvider>
        </PostHogProvider>
      </body>
    </html>
  )
}
