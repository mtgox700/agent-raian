#!/usr/bin/env node
/**
 * Brand registries are generated from the data, so a brand is only data:
 *   packages/themes/themes/<key>.json                 its paint
 *   packages/content/content/<key>/<locale>/<doc>.json its texts
 * This script writes the import lists that bundlers need (no runtime glob):
 *   packages/themes/src/registry.generated.ts
 *   packages/content/src/registry.generated.ts
 *   apps/api/lib/brand/keys.generated.ts
 * Usage: node scripts/sync-brands.mjs [--check]
 */

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const check = process.argv.includes('--check')
const HEADER = '// Generated by scripts/sync-brands.mjs from the brand data. Do not edit.\n'
const dirs = (dir) => readdirSync(dir).filter((x) => statSync(join(dir, x)).isDirectory()).sort()
const ident = (s) => s.replace(/[^a-zA-Z0-9]+(.)/g, (_, c) => c.toUpperCase()).replace(/^[^a-zA-Z]/, '_$&')

// Themes: the default brand (theme.default === true) comes first.
const themeDir = join(root, 'packages/themes/themes')
const themes = readdirSync(themeDir).filter((f) => f.endsWith('.json')).map((f) => {
  const json = JSON.parse(readFileSync(join(themeDir, f), 'utf8'))
  return { key: json.key, file: f, isDefault: json.default === true }
}).sort((a, b) => Number(b.isDefault) - Number(a.isDefault) || a.key.localeCompare(b.key))
if (themes.filter((t) => t.isDefault).length !== 1) throw new Error('Exactly one theme must have "default": true')

const themesTs = HEADER +
  themes.map((t) => `import ${ident(t.key)} from '../themes/${t.file}'`).join('\n') +
  `\n\n/** Every theme, the default one first. */\nexport const themeData: unknown[] = [${themes.map((t) => ident(t.key)).join(', ')}]\n`

// Content: every brand/locale/document file.
const contentDir = join(root, 'packages/content/content')
const docs = []
for (const brand of dirs(contentDir)) {
  for (const locale of dirs(join(contentDir, brand))) {
    for (const f of readdirSync(join(contentDir, brand, locale)).filter((x) => x.endsWith('.json')).sort()) {
      docs.push({ key: `${brand}/${locale}/${f.replace(/\.json$/, '')}`, path: `../content/${brand}/${locale}/${f}` })
    }
  }
}
const contentTs = HEADER +
  docs.map((d) => `import ${ident(d.key)} from '${d.path}'`).join('\n') +
  `\n\n/** Every bundled document, keyed \`brand/locale/document\`. */\nexport const files: Record<string, unknown> = {\n` +
  docs.map((d) => `  '${d.key}': ${ident(d.key)},`).join('\n') + '\n}\n'

// Brand keys for the app types.
const locales = Object.fromEntries(themes.map((t) => [t.key, existsSync(join(contentDir, t.key)) ? dirs(join(contentDir, t.key)) : []]))
const keysTs = HEADER +
  `export const BRAND_KEYS = [${themes.map((t) => `'${t.key}'`).join(', ')}] as const\n` +
  `/** Locales with content, per brand (the first one is the brand's locale). */\n` +
  `export const BRAND_LOCALES = ${JSON.stringify(locales)} as const\n` +
  `export type BrandKey = (typeof BRAND_KEYS)[number]\n` +
  `export const DEFAULT_BRAND: BrandKey = '${themes[0].key}'\n`

const outputs = [
  ['packages/themes/src/registry.generated.ts', themesTs],
  ['packages/content/src/registry.generated.ts', contentTs],
  ['apps/api/lib/brand/keys.generated.ts', keysTs],
]

let stale = 0
for (const [file, text] of outputs) {
  const full = join(root, file)
  const current = existsSync(full) ? readFileSync(full, 'utf8') : ''
  if (current === text) continue
  if (check) { console.error(`${file} is out of date: run node scripts/sync-brands.mjs`); stale++ }
  else { writeFileSync(full, text); console.log(`Wrote ${file}`) }
}
if (stale) process.exit(1)
if (check) console.log('Brand registries are up to date.')
